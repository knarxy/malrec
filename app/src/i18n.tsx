const PATTERNS_DE: [RegExp, (m: RegExpMatchArray) => string][] = [
  [/^directed by (.+)$/, (m) => `Regie: ${m[1]}`],
  [/^written by (.+)$/, (m) => `Drehbuch: ${m[1]}`],
  [/^based on the work of (.+)$/, (m) => `nach einem Werk von ${m[1]}`],
  [/^music by (.+)$/, (m) => `Musik: ${m[1]}`],
  [/^animated by (.+)$/, (m) => `Animation: ${m[1]}`],
  [/^(\d+)s anime$/, (m) => `${m[1]}er`],
  [/^(.+) episodes$/, (m) => `${m[1]} Folgen`],
]

export function translateLabel(lang: Lang, label: string): string {
  if (lang === 'en') return label
  if (LABELS_DE[label]) return LABELS_DE[label]
  for (const [re, f] of PATTERNS_DE) {
    const m = label.match(re)
    if (m) return f(m)
  }
  return label
}

export type T = (key: string, vars?: Record<string, string | number>) => string

export function makeT(lang: Lang): T {
  const dict = lang === 'de' ? de : en
  return (key, vars) => {
    let s = dict[key] ?? en[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
    return s
  }
}

export interface I18n { lang: Lang; t: T; label: (s: string) => string }

export const I18nContext = createContext<I18n>({
  lang: 'en', t: makeT('en'), label: (s) => s,
})

export function useI18n(): I18n {
  return useContext(I18nContext)
}

export function initialLang(): Lang {
  try {
    const v = localStorage.getItem('malrec.lang')
    if (v === 'de' || v === 'en') return v
  } catch { /* storage blocked */ }
  return navigator.language?.toLowerCase().startsWith('de') ? 'de' : 'en'
}
